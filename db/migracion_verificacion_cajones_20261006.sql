-- que vive en public y COPIA lo necesario a una tabla GP2. Las RPC de pantalla leen sólo GP2.
--
-- De dónde sale cada dato (medido el 06/10/2026):
--   * Se descartan: lo que no es producción (LT, MOV, PB, AL: Uni 0), lo borrado (Eliminar = 'S'),
--     los "[CONT]" (cajón que viene del día anterior: mezcla dos días) y el ENVASADO
--     (public."Matrices"."Tipo_Matriz" = 'E', 96 matrices).
--   * PESO POR UNIDAD: GP2.matriz.n_matriz -> ruta_paso.comp_salida_id -> componente.kg_x_uni.
--     Sólo 15 de las 38 matrices usadas en 14 días lo tienen (49% de los cajones): el sorteo
--     elige PRIMERO entre los que tienen peso y completa con los que no.
--     Una matriz puede sacar más de una pieza (la 12: 0,0355 / 0,0388 / 0,0396 kg): se guarda el
--     rango y el peso esperado es "entre X y Y". La 501 (piedra) se carga en KG
--     (GP2.matriz.carga_en = 'kg'): su peso esperado son las unidades cargadas.
--   * SECTOR donde puede estar = el sector de esa pieza (componente.sector_id).
--   * Entre los que tienen peso, de operarios DISTINTOS: el 05/10, 9 de los 11 cajones con peso
--     eran de la misma persona y la misma matriz.
--
-- Todo queda COPIADO al sortear: si después cambia GP2 o el registro de producción, lo verificado
-- sigue diciendo lo que decía ese día.
